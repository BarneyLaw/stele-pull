const requestUrl = vi.hoisted(() => vi.fn());
vi.mock("obsidian", async (orig) => ({ ...(await orig<object>()), requestUrl }));

const schema = (name: string) =>
  readFileSync(fileURLToPath(new URL(`../../schema/${name}`, import.meta.url)), "utf8");

interface PathFixture {
  folders: CanvasFolder[];
  files: CanvasFile[];
  expect: { canvas_id: number; path: string; state: string; renamed: boolean }[];
}

describe("paths: the worker's, from the same Canvas listing", () => {
  // Generated by internal/run/paths_contract_test.go from the worker's own
  // path builder. A vault switched between modes must not move a single file.
  const fx = JSON.parse(schema("canvas-paths.json")) as PathFixture;
  const got = new Map(canvasEntries(fx.files, fx.folders).map((e) => [e.canvas_id, e]));

  it("plans exactly the files the worker plans", () => {
    expect([...got.keys()].sort((a, b) => a - b)).toEqual(fx.expect.map((x) => x.canvas_id));
  });

  for (const want of fx.expect) {
    it(`file ${want.canvas_id} -> ${JSON.stringify(want.path)}`, () => {
      const e = got.get(want.canvas_id)!;
      expect(e.path).toBe(want.path);
      expect(e.state).toBe(want.state);
      // The worker notes a stand-in name; its wording is its own.
      if (want.state === "stored") expect(Boolean(e.reason)).toBe(want.renamed);
    });
  }
});

const T0 = "2026-08-11T02:15:00Z";
const T1 = "2026-09-12T09:30:00Z";
const NOW = new Date("2026-10-23T00:00:00Z");
const COURSE = { id: 42, name: "TST1001 Testing [2610]", course_code: "TST1001" };
const FOLDERS: CanvasFolder[] = [{ id: 1, full_name: "course files" }];

function file(id: number, name: string, over: Partial<CanvasFile> = {}): CanvasFile {
  return {
    id, folder_id: 1, display_name: name, size: 5, updated_at: T0, modified_at: T0,
    url: `https://canvas.example/files/${id}/download?verifier=v${id}`, ...over,
  };
}

const rec = (sha: string, over: Partial<FileRecord> = {}): FileRecord => ({
  sha256: sha, size: 5, writtenAt: 0, canvasId: 1, updatedAt: T0, modifiedAt: T0, ...over,
});

describe("canvasManifest", () => {
  it("takes the hash of a file unchanged since this device wrote it", () => {
    const m = canvasManifest(COURSE, [file(1, "a.pdf")], FOLDERS, { "a.pdf": rec("aa") }, NOW);
    expect(m.entries[0]).toMatchObject({ path: "a.pdf", state: "stored", sha256: "aa" });
  });

  it("matches timestamps as instants, not strings", () => {
    // A record written from a worker manifest, read back against Canvas's own spelling.
    const m = canvasManifest(COURSE, [file(1, "a.pdf", { updated_at: "2026-08-11T10:15:00+08:00" })],
      FOLDERS, { "a.pdf": rec("aa") }, NOW);
    expect(m.entries[0]!.sha256).toBe("aa");
  });

  it.each([
    ["re-uploaded under a new id", { id: 2 }],
    ["resized", { size: 6 }],
    ["updated", { updated_at: T1 }],
    ["modified", { modified_at: T1 }],
  ])("leaves the hash unknown for a file %s", (_, over) => {
    const m = canvasManifest(COURSE, [file(1, "a.pdf", over)], FOLDERS, { "a.pdf": rec("aa") }, NOW);
    expect(m.entries[0]!.sha256).toBeUndefined();
  });

  it("leaves the hash unknown when the record predates Canvas metadata", () => {
    const old: FileRecord = { sha256: "aa", size: 5, writtenAt: 0 };
    const m = canvasManifest(COURSE, [file(1, "a.pdf")], FOLDERS, { "a.pdf": old }, NOW);
    expect(m.entries[0]!.sha256).toBeUndefined();
  });

  it("tombstones what this device wrote and Canvas no longer lists", () => {
    const m = canvasManifest(COURSE, [file(1, "a.pdf")], FOLDERS,
      { "a.pdf": rec("aa"), "gone.pdf": rec("bb", { canvasId: 9 }) }, NOW);
    expect(m.entries.find((e) => e.path === "gone.pdf")).toMatchObject({
      state: "deleted", canvas_id: 9, deleted_at: NOW.toISOString(),
    });
  });

  it("catalogues a locked file with its unlock date, and never a hash", () => {
    const m = canvasManifest(COURSE,
      [file(1, "a.pdf", { locked_for_user: true, unlock_at: T1, url: undefined })],
      FOLDERS, { "a.pdf": rec("aa") }, NOW);
    expect(m.entries[0]).toMatchObject({ state: "locked", unlock_at: T1 });
    expect(m.entries[0]!.sha256).toBeUndefined();
  });

  it("names the course as the worker does", () => {
    const m = canvasManifest(COURSE, [], FOLDERS, {}, NOW);
    expect(m).toMatchObject({ course_id: 42, course_code: "TST1001", course_name: COURSE.name, entries: [] });
  });

  it("gives a listing the same run id every time, and a new one when it changes", () => {
    const id = (files: CanvasFile[]) => canvasManifest(COURSE, files, FOLDERS, {}, NOW).run_id;
    const a = [file(1, "a.pdf"), file(2, "b.pdf")];
    expect(id(a)).toBe(id([...a].reverse()));
    expect(id(a)).toMatch(/^canvas-[0-9a-f]{16}$/);
    expect(id([file(1, "a.pdf"), file(2, "b.pdf", { updated_at: T1 })])).not.toBe(id(a));
  });
});

type Reply = { status: number; json?: unknown; text?: string; headers?: Record<string, string>; arrayBuffer?: ArrayBuffer };

/** Answers requestUrl from a table of url -> reply, recording each request. */
function serve(routes: Record<string, Reply>) {
  requestUrl.mockImplementation((p: RequestUrlParam) => {
    const r = routes[p.url];
    if (!r) return Promise.resolve({ status: 404, text: "{}", json: {}, headers: {}, arrayBuffer: new ArrayBuffer(0) });
    return Promise.resolve({
      status: r.status, json: r.json, text: r.text ?? JSON.stringify(r.json ?? {}),
      headers: r.headers ?? {}, arrayBuffer: r.arrayBuffer ?? new ArrayBuffer(0),
    });
  });
}

const sent = () => requestUrl.mock.calls.map((c) => c[0] as RequestUrlParam);
const B = "https://canvas.example";

// Braces matter: a function returned from beforeEach runs as a cleanup hook.
beforeEach(() => {
  requestUrl.mockReset();
});

describe("CanvasClient", () => {
  it("follows every next page, with the token on each", async () => {
    serve({
      [`${B}/api/v1/courses/42/files?per_page=100`]: {
        status: 200, json: [file(1, "a.pdf")],
        headers: { Link: `<${B}/api/v1/courses/42/files?page=2&per_page=100>; rel="next", <x>; rel="last"` },
      },
      [`${B}/api/v1/courses/42/files?page=2&per_page=100`]: { status: 200, json: [file(2, "b.pdf")] },
    });

    const files = await new CanvasClient(B, "tok").files(42);

    expect(files.map((f) => f.id)).toEqual([1, 2]);
    expect(sent().every((p) => p.headers?.Authorization === "Bearer tok")).toBe(true);
  });

  it("refuses to follow a next page to another host with the token", async () => {
    serve({
      [`${B}/api/v1/courses/42/files?per_page=100`]: {
        status: 200, json: [], headers: { link: `<https://evil.example/steal>; rel="next"` },
      },
    });

    await expect(new CanvasClient(B, "tok").files(42)).rejects.toThrow(/refusing to send the Canvas token/);
    expect(sent().map((p) => p.url)).toEqual([`${B}/api/v1/courses/42/files?per_page=100`]);
  });

  it("stops a pagination loop", async () => {
    const first = `${B}/api/v1/courses/42/files?per_page=100`;
    serve({ [first]: { status: 200, json: [], headers: { link: `<${first}>; rel="next"` } } });
    await expect(new CanvasClient(B, "tok").files(42)).rejects.toThrow(/pagination loop/);
  });

  it("downloads without the token: the url carries its own verifier", async () => {
    const url = `${B}/files/1/download?verifier=v1`;
    serve({ [url]: { status: 200, arrayBuffer: new ArrayBuffer(5) } });

    await new CanvasClient(B, "tok").download(url);

    expect(sent()[0]!.headers?.Authorization).toBeUndefined();
  });

  it("insists on 206 for a range, as the store transport does", async () => {
    const url = `${B}/files/1/download?verifier=v1`;
    serve({ [url]: { status: 200, arrayBuffer: new ArrayBuffer(10) } });

    await expect(new CanvasClient(B, "tok").download(url, { offset: 0, length: 4 })).rejects.toThrow(/ignored the Range/);
    expect(sent()[0]!.headers?.Range).toBe("bytes=0-3");
  });

  it("tells a dead token from a course it may not see", async () => {
    serve({
      [`${B}/api/v1/courses/1/files?per_page=100`]: { status: 401, json: { errors: [{ message: "Invalid access token." }] } },
      [`${B}/api/v1/courses/2/files?per_page=100`]: { status: 401, json: { status: "unauthorized", errors: [{ message: "user not authorized to perform that action" }] } },
    });
    const c = new CanvasClient(B, "tok");

    await expect(c.files(1)).rejects.toMatchObject({ kind: "unauthorized" });
    await expect(c.files(2)).rejects.toMatchObject({ kind: "forbidden" });
  });

  it("reports a course Canvas does not know as null, not an error", async () => {
    serve({});
    expect(await new CanvasClient(B, "tok").course(7)).toBeNull();
  });

  it("does not mistake the token for an error message", async () => {
    serve({ [`${B}/api/v1/courses/1`]: { status: 500, text: "boom" } });
    const err = await new CanvasClient(B, "secret-token").course(1).catch((e: unknown) => e);
    expect(err).toBeInstanceOf(CanvasError);
    expect(String((err as Error).message)).not.toContain("secret-token");
  });
});

