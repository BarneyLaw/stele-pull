// The plugin's direct-Canvas mode builds paths from a Canvas listing itself.
// It must land every file exactly where the worker would, or switching a vault
// between modes moves and re-downloads files. This test writes the worker's
// answer for a hostile listing to schema/canvas-paths.json, and
// plugin/src/canvas.test.ts runs the same listing through its own port.
//
//	go test ./internal/run -run TestCanvasPathsFixture -update
var update = flag.Bool("update", false, "rewrite schema/canvas-paths.json from the worker's path builder")

type pathFixture struct {
	Comment []string        `json:"_comment"`
	Folders []canvas.Folder `json:"folders"`
	Files   []canvas.File   `json:"files"`
	Expect  []pathExpect    `json:"expect"`
}

type pathExpect struct {
	CanvasID int64  `json:"canvas_id"`
	Path     string `json:"path"`
	State    string `json:"state"`
	// Renamed: the Canvas name could not be made portable and a stand-in was
	// used. The note's wording is the worker's own and is not compared.
	Renamed bool `json:"renamed"`
}

func hostileListing() ([]canvas.Folder, []canvas.File) {
	long := strings.Repeat("x", 110)
	folders := []canvas.Folder{
		{ID: 1, FullName: "course files"},
		{ID: 2, FullName: "course files/Week 1"},
		{ID: 3, FullName: "course files/Week 1/Lab: Sockets?"},
		{ID: 4, FullName: "course files/Résumé"}, // NFD, as macOS uploads it
		{ID: 5, FullName: "course files/trailing. "},
		{ID: 6, FullName: "course files/" + long + "/" + long + "/" + long + "/" + long},
	}
	t0 := time.Date(2026, 8, 11, 2, 15, 0, 0, time.UTC)
	t1 := time.Date(2026, 9, 12, 9, 30, 0, 0, time.UTC)
	f := func(id, folder int64, name string) canvas.File {
		return canvas.File{ID: id, FolderID: folder, DisplayName: name, Size: id * 10,
			UpdatedAt: t0, ModifiedAt: t0, ContentType: "application/pdf"}
	}
	unlock := time.Date(2026, 11, 1, 0, 0, 0, 0, time.UTC)
	locked := f(117, 2, "future.pdf")
	locked.LockedForUser, locked.UnlockAt = true, &unlock
	staff := f(124, 2, "answers.pdf")
	staff.Locked = true
	renamed := f(102, 2, "Lecture 1 v2.pdf") // the same id again, newer: it wins
	renamed.UpdatedAt = t1
	files := []canvas.File{
		f(101, 1, "syllabus.pdf"),
		f(102, 2, "Lecture 1.pdf"),
		renamed,
		f(103, 3, "lab<1>|2*.pdf"),
		f(104, 2, "Slides.PDF"),
		f(105, 2, "slides.pdf"), // collides with 104 on a case-insensitive disk
		f(106, 1, "CON.txt"),
		f(107, 1, "com1"),
		f(121, 1, "AUX.tar.gz"),
		f(108, 4, "étude.pdf"),
		f(109, 1, strings.Repeat("long name ", 20)+".pdf"),
		f(110, 1, strings.Repeat("講義", 30)+".pdf"), // 3 bytes a rune: truncated by bytes
		f(111, 1, ".."),
		f(112, 1, "   "),
		f(122, 1, "\a\a.verylongextensionname"),
		f(113, 5, "notes.txt "),
		f(114, 99, "orphan.pdf"), // folder missing from the listing
		f(115, 1, "a\tb\u0007c.pdf"),
		f(116, 1, `back\slash/and.pdf`),
		locked,
		staff,
		f(118, 1, "syllabus.pdf"), // same path as 101, different file
		f(119, 1, strings.Repeat("y", 116)+".pdf"),
		f(120, 1, strings.Repeat("y", 116)+".pdf"), // collides at the length limit
		f(125, 1, "trailing dots....pdf..."),
		f(123, 6, "deep.pdf"), // path over the total length limit
	}
	return folders, files
}

func TestCanvasPathsFixture(t *testing.T) {
	folders, files := hostileListing()
	byID := make(map[int64]canvas.Folder, len(folders))
	for _, fo := range folders {
		byID[fo.ID] = fo
	}
	pf, _ := toPlanFiles(slog.New(slog.NewTextHandler(io.Discard, nil)), files, byID, &Stats{})
	p := plan.Compute(plan.Input{
		CourseID: 1, Files: pf, Now: now,
		Policy: &policy.Policy{Version: 1, Default: policy.ActionInclude},
	})

	renamed := map[int64]bool{}
	for _, f := range pf {
		renamed[f.CanvasID] = f.Note != ""
	}
	var expect []pathExpect
	for _, f := range p.Fetch {
		expect = append(expect, pathExpect{f.CanvasID, f.Path, "stored", renamed[f.CanvasID]})
	}
	for _, e := range p.Locked {
		expect = append(expect, pathExpect{e.CanvasID, e.Path, string(e.State), renamed[e.CanvasID]})
	}
	sort.Slice(expect, func(i, j int) bool { return expect[i].CanvasID < expect[j].CanvasID })
	if len(expect) != len(files)-1 { // 102 is listed twice
		t.Fatalf("planned %d files from a listing of %d distinct ids", len(expect), len(files)-1)
	}

	out, err := json.MarshalIndent(pathFixture{
		Comment: []string{
			"Generated by internal/run/paths_contract_test.go. Do not edit by hand:",
			"go test ./internal/run -run TestCanvasPathsFixture -update",
			"",
			"A Canvas listing and the vault path the worker gives each file.",
			"The plugin's direct-Canvas mode must produce the same paths.",
		},
		Folders: folders, Files: files, Expect: expect,
	}, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	checkSchemaFixture(t, "canvas-paths.json", append(out, '\n'))
}

func checkSchemaFixture(t *testing.T, name string, want []byte) {
	t.Helper()
	path := filepath.Join("..", "..", "schema", name)
	if *update {
		if err := os.WriteFile(path, want, 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %s", path)
		return
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%s missing; generate it with -update: %v", name, err)
	}
	// A Windows checkout may have converted line endings.
	got = bytes.ReplaceAll(got, []byte("\r\n"), []byte("\n"))
	if !bytes.Equal(got, want) {
		t.Errorf("schema/%s does not match the worker's path builder (stale or hand-edited).\n"+
			"Regenerate: go test ./internal/run -run TestCanvasPathsFixture -update", name)
	}
}
